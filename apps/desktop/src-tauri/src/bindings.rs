//! CONTRACT (lead): the registry of every command and event exposed to the
//! frontend. `cargo test -p desktop export_bindings` regenerates
//! `apps/desktop/src/bindings.ts`; CI fails if the committed file differs.

use tauri_specta::{collect_commands, collect_events, Builder};

use crate::commands::{
    accounts, app, content, instances, java, loaders, rooms, settings, skins, system, tasks,
    versions, voice, vpn,
};
use crate::events::*;

pub const BINDINGS_HEADER: &str = "// AUTO-GENERATED by `cargo test -p desktop export_bindings`. DO NOT EDIT.\n// Contract owner: lead. See docs/CONTRACTS.md.";

