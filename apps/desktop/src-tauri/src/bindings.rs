#[cfg(test)]
mod tests {
    use specta_typescript::Typescript;

    use super::*;

    #[test]
    fn export_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");
        specta_builder()
            .export(Typescript::default().header(BINDINGS_HEADER), path)
            .expect("export bindings.ts");
    }
}
