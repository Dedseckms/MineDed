//! Library entries of loader version jsons / install profiles.

use std::path::{Path, PathBuf};

use lc_http::{DownloadReq, ResourceKind};
use lc_types::AppResult;
use serde::{Deserialize, Serialize};

use crate::util::{maven_path, parse_url, safe_join};

pub(crate) const MOJANG_LIBRARIES: &str = "https://libraries.minecraft.net/";

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub(crate) struct Library {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sha1: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub size: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub downloads: Option<LibDownloads>,
    /// Platform rules / natives: such libraries are left to core.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rules: Option<serde_json::Value>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub natives: Option<serde_json::Value>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub(crate) struct LibDownloads {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifact: Option<LibArtifact>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub(crate) struct LibArtifact {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sha1: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub size: Option<u64>,
    #[serde(default)]
    pub url: String,
}

/// Where a library lives and how to get it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct LibFile {
    /// Repository-relative path (`/`-separated).
    pub path: String,
    /// `None` = not downloadable (generated by processors or bundled in the installer).
    pub url: Option<String>,
    pub sha1: Option<String>,
    pub size: Option<u64>,
}

impl LibFile {
    pub fn local(&self, libraries: &Path) -> AppResult<PathBuf> {
        safe_join(libraries, &self.path)
    }
}

fn join_repo(base: &str, path: &str) -> String {
    if base.ends_with('/') {
        format!("{base}{path}")
    } else {
        format!("{base}/{path}")
    }
}

impl Library {
    /// The main artifact; `None` for platform-specific (ruled/natives) entries.
    pub fn file(&self) -> Option<LibFile> {
        if self.rules.is_some() || self.natives.is_some() {
            return None;
        }
        match self.downloads.as_ref().and_then(|d| d.artifact.as_ref()) {
            Some(a) => {
                let path = a.path.clone().or_else(|| maven_path(&self.name))?;
                Some(LibFile {
                    path,
                    url: (!a.url.is_empty()).then(|| a.url.clone()),
                    sha1: a.sha1.clone(),
                    size: a.size,
                })
            }
            None => {
                let path = maven_path(&self.name)?;
                let repo = self.url.as_deref().unwrap_or(MOJANG_LIBRARIES);
                Some(LibFile {
                    url: Some(join_repo(repo, &path)),
                    path,
                    sha1: self.sha1.clone(),
                    size: self.size,
                })
            }
        }
    }
}

/// Download requests for every downloadable library (deduplicated).
pub(crate) fn library_requests(libs: &[Library], libraries: &Path) -> AppResult<Vec<DownloadReq>> {
    let mut seen = std::collections::HashSet::new();
    let mut out = Vec::new();
    for lib in libs {
        let Some(f) = lib.file() else { continue };
        let Some(url) = &f.url else { continue };
        let dest = f.local(libraries)?;
        if seen.insert(dest.clone()) {
            out.push(DownloadReq {
                urls: vec![parse_url(url)?],
                sha1: f.sha1.clone(),
                size: f.size,
                dest,
                kind: ResourceKind::Library,
            });
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fabric_and_forge_styles() {
        let fabric: Library = serde_json::from_str(
            r#"{"name":"net.fabricmc:fabric-loader:0.16.9","url":"https://maven.fabricmc.net/","sha1":"ab","size":3}"#,
        )
        .unwrap();
        let f = fabric.file().unwrap();
        assert_eq!(
            f.url.as_deref(),
            Some("https://maven.fabricmc.net/net/fabricmc/fabric-loader/0.16.9/fabric-loader-0.16.9.jar")
        );
        assert_eq!(f.sha1.as_deref(), Some("ab"));

        let forge: Library = serde_json::from_str(
            r#"{"name":"net.minecraftforge:forge:1.20.1-47.3.0:client","downloads":{"artifact":{"path":"net/minecraftforge/forge/1.20.1-47.3.0/forge-1.20.1-47.3.0-client.jar","url":"","sha1":"cd"}}}"#,
        )
        .unwrap();
        let f = forge.file().unwrap();
        assert_eq!(f.url, None);
        let reqs = library_requests(&[fabric, forge], Path::new("/libs")).unwrap();
        assert_eq!(reqs.len(), 1);
    }
}
